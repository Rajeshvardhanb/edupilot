import type { NextRequest } from "next/server";
import { getCurrentUser } from "@/lib/auth";
import { DATASETS, toCsv } from "@/lib/reports";
import { Doc, pdfResponse } from "@/lib/pdf";
import { audit } from "@/lib/audit";
import { isoDate } from "@/lib/format";

export async function GET(req: NextRequest) {
  const user = await getCurrentUser();
  const sp = req.nextUrl.searchParams;
  const key = sp.get("dataset") ?? "";
  const ds = DATASETS[key];
  if (!user || !ds || !ds.roles.includes(user.role)) return new Response("Forbidden", { status: 403 });
  const wanted = sp.getAll("cols");
  const cols = ds.columns.filter((c) => (wanted.length ? wanted.includes(c.key) : c.default));
  const rows = await ds.rows(user, { program: sp.get("program") ?? "", batch: sp.get("batch") ?? "", from: sp.get("from") ?? "", to: sp.get("to") ?? "" });
  const table = rows.map((r) => cols.map((c) => r[c.key] ?? ""));
  const name = `${key}-${isoDate(new Date())}`;
  await audit(user.id, "EXPORT", "Report", key, `${rows.length} rows · ${sp.get("format") ?? "csv"}`);

  if (sp.get("format") === "pdf") {
    const doc = await Doc.create({ landscape: cols.length > 6 });
    await doc.letterhead(`${ds.label} report`, isoDate(new Date()));
    doc.table(cols.map((c) => c.label), table, { size: cols.length > 9 ? 7 : 8 });
    return pdfResponse(await doc.finish(`${ds.label} · ${rows.length} rows · generated by ${user.name}`), `${name}.pdf`);
  }
  return new Response(toCsv(cols.map((c) => c.label), table), { headers: { "Content-Type": "text/csv; charset=utf-8", "Content-Disposition": `attachment; filename="${name}.csv"` } });
}
